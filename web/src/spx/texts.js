/** Pépé Gogol's answer: gibberish, a few made-up words. */
export function gibberish(random = Math.random) {
  const bits = ['bl', 'gna', 'frou', 'mblé', 'glou', 'ouin', 'brr', 'keuh', 'pfou', 'gneu', 'blo', 'zou', 'mmh', 'ga'];
  const words = 3 + Math.floor(random() * 3);
  const out = [];
  for (let i = 0; i < words; i++) {
    let w = '';
    const n = 1 + Math.floor(random() * 3);
    for (let k = 0; k < n; k++) w += bits[Math.floor(random() * bits.length)];
    out.push(w);
  }
  const text = out.join(' ');
  return text[0].toUpperCase() + text.slice(1) + (random() < 0.5 ? ' !' : '…');
}

/** The translator: TEXTS[lang] first, then English, then the key; {name} placeholders filled. Arrays pick one at random. */
export function createTexts(lang, random = Math.random) {
  const own = TEXTS[lang] || TEXTS.en;
  return (key, vars = {}) => {
    let text = own[key] !== undefined ? own[key] : TEXTS.en[key];
    if (text === undefined) return key;
    if (Array.isArray(text)) text = text[Math.floor(random() * text.length)];
    return String(text).replace(/\{(\w+)\}/g, (_, name) => (vars[name] !== undefined ? String(vars[name]) : ''));
  };
}
